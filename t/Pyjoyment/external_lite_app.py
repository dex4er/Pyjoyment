import Pyjo.Test.Pyjo

from Pyjo.File import curfile
from Pyjo.Test import *

import os


# BEGIN { $ENV{MOJO_MODE} = 'testing' }, before the mode of the application is read
os.environ['PYJO_MODE'] = 'testing'

# Left out from Mojolicious: MOJO_REACTOR, as the tests run on the reactor of Pyjo.Reactor.detect()

# Renamed from Mojolicious: the external applications are in tt/external, where Mojo has them in t/mojolicious/external,
# and the script is myapp.py, where Mojo has myapp.pl
myapp = curfile().dirname().dirname().dirname().child('tt', 'external', 'myapp.py')

t = Pyjo.Test.Pyjo.new(myapp)

with subtest('Template from myapp.py'):
    # Renamed from Mojolicious: the package of a configuration file, Mojolicious::Plugin::Config::Sandbox, is the module
    # Pyjoyment.Plugin.Config.Sandbox
    t.get_ok('/').status_is(200).content_is("""\
myapp
works ♥!Insecure!Insecure!

too!works!!!Pyjoyment.Plugin.Config.Sandbox
<a href="/">Test</a>
<form action="/%E2%98%83">
  <input type="submit" value="☃">
</form>
""")

with subtest('Static file from myapp.py'):
    t.get_ok('/index.html').status_is(200).content_is('External static file!\n')

with subtest('Echo from myapp.py'):
    t.get_ok('/echo').status_is(200).content_is('echo: nothing!')

with subtest('Chunked response from myapp.py'):
    t.get_ok('/stream').status_is(200).content_is('hello!')

with subtest('URL generated by myapp.py'):
    t.get_ok('/url/☃').status_is(200).content_is('/url/%E2%98%83.json -> /%E2%98%83/stream!')

with subtest('Config value at startup time'):
    t.get_ok('/startup').status_is(200).content_is('Insecure!')

# Config override
t = Pyjo.Test.Pyjo.new(myapp, {'one': 'override!', 'two': 'go!', 'just': 'yada', 'works': 'override two!'})

with subtest('Template from myapp.py with config override'):
    t.get_ok('/').status_is(200).content_is("""\
myapp
yadaoverride!go!

override two!*?
<a href="/">Test</a>
<form action="/%E2%98%83">
  <input type="submit" value="☃">
</form>
""")

with subtest('Config override at startup time'):
    t.get_ok('/startup').status_is(200).content_is('override!')

done_testing()
