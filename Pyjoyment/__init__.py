    def handler(self, tx: Any) -> None:
        """::

            app.handler(Pyjo.Transaction.HTTP.new())
            app.handler(Pyjoyment.Controller.new())

        Sets up the default controller and emits the ``around_dispatch`` hook
        for every request.
        """
        # Dispatcher has to be last in the chain
        if not self._dispatch:
            self._dispatch = True
            self.hook('around_action', _action)
            self.hook('around_dispatch', _dispatch)

        # Process with chain
        c = self.build_controller(tx)
        self.plugins.emit_chain('around_dispatch', c)

        # Delayed response
        if not c.stash().get('mojo.rendered'):
            c.helpers.log().trace('Nothing has been rendered, expecting delayed response (see FAQ for more)')

