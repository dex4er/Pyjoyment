    def build_controller(self, tx: Any = None) -> Pyjoyment.Controller.object:
        """::

            c = app.build_controller()
            c = app.build_controller(Pyjo.Transaction.HTTP.new())
            c = app.build_controller(Pyjoyment.Controller.new())

        Build default controller object with :attr:`controller_class`. ::

            # Render template from application
            foo = app.build_controller().render_to_string(template='foo')
        """
        # Embedded application
        stash: dict[str, Any] = {}
        if tx is not None and isinstance(tx, Pyjoyment.Controller.object):
            stash, tx = tx.stash(), tx.tx

        # Build default controller
        stash.update(self.defaults())
        cls = self.controller_class
        if isinstance(cls, str):
            cls = Pyjo.Loader._class(cls) or Pyjoyment.Controller.object  # pyright: ignore[reportPrivateUsage]
        cls = cast(type[Pyjoyment.Controller.object], cls)
        c = cls.new(app=self, stash=stash, tx=tx)
        if c.tx is None:
            # The controller keeps the transaction, as Mojo keeps it in the hash of the controller
            c._own_tx = own = self.build_tx()  # pyright: ignore[reportPrivateUsage]
            c.tx = own

        return c

    def build_tx(self) -> Pyjo.Transaction.HTTP.object:
        """::

            tx = app.build_tx()

        Build :mod:`Pyjo.Transaction.HTTP` object and emit ``after_build_tx``
        hook.
        """
        tx = Pyjo.Transaction.HTTP.new()
        if (max := self.max_request_size) is not None:
            tx.req.max_message_size = max
        self.plugins.emit_hook('after_build_tx', tx, self)

        return tx

